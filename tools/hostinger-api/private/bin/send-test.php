<?php
// Send a real test email through the configured SMTP account.
//   php ~/portfolio-api/bin/send-test.php you@example.com            (sends a plain test email)
//   php ~/portfolio-api/bin/send-test.php you@example.com --debug    (also prints the SMTP conversation, passwords redacted)
//   php ~/portfolio-api/bin/send-test.php you@example.com --templates (sends both real templates with sample data)
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
require dirname(__DIR__) . '/bootstrap.php';

$to = $argv[1] ?? '';
$debug = in_array('--debug', $argv, true);
$templates = in_array('--templates', $argv, true);
if (!email_ok($to)) { fwrite(STDERR, "Usage: php bin/send-test.php you@example.com [--debug] [--templates]\n"); exit(2); }
if ($p = config_problems()) fwrite(STDERR, 'Note — config.php still has template values for: ' . implode(', ', $p) . "\n");

echo 'SMTP ', cfgv('smtp.host'), ':', cfgv('smtp.port'), ' (', cfgv('smtp.secure'), ') as ', cfgv('smtp.username'), "\n";
echo 'From ', cfg('from_email'), ' → ', $to, "\n\n";

if ($templates) {
  $s = ['ref' => 'E' . gmdate('ymd') . '-TEST01', 'source' => 'project-request', 'created_at' => gmdate('c'), 'name' => 'Test Sender', 'email' => $to,
    'phone' => '+880 1700 000000', 'company' => 'Example Ltd', 'services' => 'Website, CRM & automation', 'budget' => 'Prefer to discuss', 'timeline' => 'Within 1–2 months',
    'message' => "This is a sample enquiry generated by bin/send-test.php to preview the email templates.\nNothing here was submitted by a real person.",
    'details_arr' => ['country' => 'Bangladesh', 'industry' => 'Retail & eCommerce'], 'details' => null, 'blueprint' => '', 'page' => '/solutions/', 'consent' => 1];
  $vars = ['s' => $s, 'source' => sources()['project-request'], 'brand' => (array)cfg('brand'), 'proposal' => null, 'when' => gmdate('j M Y, H:i') . ' UTC', 'whenUtc' => gmdate('Y-m-d H:i'),
    'responseTime' => (string)cfg('response_time'), 'ownerName' => (string)cfg('owner_name')];
  foreach (['admin-notification', 'client-confirmation'] as $t) {
    $m = render_email($t, $vars);
    $r = send_mail([$to, ''], '[TEST] ' . $m['subject'], $m['html'], $m['text']);
    echo str_pad($t, 22), $r['ok'] ? "accepted by the SMTP server\n" : "FAILED: {$r['error']}\n";
  }
  exit;
}

try {
  $m = make_mailer($debug);
  $m->addAddress($to);
  $m->Subject = 'SMTP test from your website — ' . gmdate('Y-m-d H:i') . ' UTC';
  $m->Body = "This is a test from your website's email system (bin/send-test.php).\nIf you can read this, SMTP delivery works.";
  $m->send();
  log_event('info', 'test_email', ['to' => mask_email($to), 'ok' => true]);
  echo "\nAccepted by the SMTP server. Now check the inbox (and the spam folder) of $to.\n";
} catch (\Throwable $e) {
  $cat = mail_error_category((isset($m) ? $m->ErrorInfo : '') . ' ' . $e->getMessage());
  log_event('error', 'test_email', ['to' => mask_email($to), 'ok' => false, 'category' => $cat]);
  fwrite(STDERR, "\nFAILED: $cat\n" . (isset($m) ? str_replace((string)cfgv('smtp.password', '') ?: "\0", '[redacted]', $m->ErrorInfo) : '') . "\nRun again with --debug to see the SMTP conversation.\n");
  exit(1);
}
